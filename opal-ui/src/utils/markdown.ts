import DOMPurify, { type UponSanitizeAttributeHookEvent } from 'isomorphic-dompurify';
import type { MarkdownIt } from 'markdown-it';

// Elements DOMPurify allows by default that could still alter the page around the markdown, or load external
// resources (tracking) when the page is displayed: media have no use case in Opal metadata.
const FORBID_TAGS = [
  'style',
  'form',
  'input',
  'button',
  'textarea',
  'select',
  'option',
  'img',
  'svg',
  'image',
  'video',
  'audio',
  'source',
  'track',
  'picture',
];
// Markdown tables render the column alignment as an inline style on cells.
const CELL_ALIGN = /^text-align:(left|center|right)$/;

// Classes generated by q-markdown and its Prism code highlighting (styled by the qmarkdown CSS).
const MARKDOWN_CLASS = /^(q-markdown--[\w-]+|language-[\w-]+|non-selectable)$/;
const PRISM_CLASSES = new Set([
  'token',
  'atrule',
  'attr-name',
  'attr-value',
  'block-comment',
  'bold',
  'boolean',
  'builtin',
  'cdata',
  'char',
  'class-name',
  'comment',
  'constant',
  'cr',
  'deleted',
  'doctype',
  'entity',
  'function',
  'function-name',
  'important',
  'inserted',
  'italic',
  'keyword',
  'lf',
  'number',
  'operator',
  'prolog',
  'property',
  'punctuation',
  'regex',
  'selector',
  'string',
  'style',
  'symbol',
  'tab',
  'tag',
  'url',
  'variable',
]);

// Inline styles could overlay the page (e.g. position: fixed): only the table cell alignment is kept.
function filterStyle(node: Element, data: UponSanitizeAttributeHookEvent) {
  const isCell = node.tagName === 'TH' || node.tagName === 'TD';
  if (!isCell || !CELL_ALIGN.test(data.attrValue)) {
    data.keepAttr = false;
  }
}

// Application classes (e.g. Quasar's fixed-full, z-max) could overlay the page as well: only the classes generated
// by q-markdown are kept.
function filterClass(data: UponSanitizeAttributeHookEvent) {
  const classes = data.attrValue
    .split(/\s+/)
    .filter((name) => MARKDOWN_CLASS.test(name) || PRISM_CLASSES.has(name));
  if (classes.length === 0) {
    data.keepAttr = false;
  } else {
    data.attrValue = classes.join(' ');
  }
}

function filterAttribute(node: Element, data: UponSanitizeAttributeHookEvent) {
  if (data.attrName === 'style') filterStyle(node, data);
  else if (data.attrName === 'class') filterClass(data);
}

// Any target opens another browsing context that would get access to the opener.
function forceSafeRel(node: Element) {
  if (node.tagName === 'A' && node.hasAttribute('target')) {
    node.setAttribute('rel', 'noopener noreferrer');
  }
}

/**
 * Sanitizes the HTML rendered from markdown: scripts, event handlers and dangerous URLs are removed, the
 * markdown formatting and harmless inline HTML are kept.
 */
export function sanitizeHtml(html: string): string {
  DOMPurify.addHook('uponSanitizeAttribute', filterAttribute);
  DOMPurify.addHook('afterSanitizeAttributes', forceSafeRel);
  try {
    return DOMPurify.sanitize(html, { FORBID_TAGS, ADD_ATTR: ['target'] });
  } finally {
    DOMPurify.removeHook('uponSanitizeAttribute', filterAttribute);
    DOMPurify.removeHook('afterSanitizeAttributes', forceSafeRel);
  }
}

/**
 * markdown-it plugin that sanitizes the rendered output. Raw HTML is allowed in markdown sources (variable labels,
 * descriptions, annotations etc.) which are user supplied, so the output must be sanitized before being injected.
 */
export function sanitizePlugin(md: MarkdownIt) {
  const render = md.render.bind(md);
  const renderInline = md.renderInline.bind(md);
  md.render = (src, env) => sanitizeHtml(render(src, env));
  md.renderInline = (src, env) => sanitizeHtml(renderInline(src, env));
}
